-- 004：两层结构收敛（2026-09-30 用户拍板：三层 → 必填 / 弹性）
--
-- 原「建议层」并入弹性层：语义上两者都是「想做、可挪」，
-- 合并后少一个概念，而「必填 = 必须在那一刻做」成为唯一会打扰用户的层。
--
-- 注意：`blocks.layer` 列上的物理默认值仍是 'suggested'
-- （SQLite 不能修改已建列的默认值，除非重建表 —— 不值得）。
-- 因此**代码一律显式写入层值**，本迁移只负责把老数据一次性转换过来。
-- 它天然幂等：第二次跑的时候已经没有 layer='suggested' 的行了。
UPDATE blocks SET layer = 'elastic' WHERE layer = 'suggested';
